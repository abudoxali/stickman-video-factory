// Procedural cartoon SFX pack (own work, CC0) rendered with FFmpeg expressions:
// whooshes, slide whistles, a spring "boing", apple crunches and a pop — the
// classic cartoon sounds the Kenney CC0 packs do not include. Deterministic
// (seeded noise), so the pack is reproducible byte-for-byte from this script.
// Usage: node scripts/make-sfx.mjs && npm run assets
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const OUT = "public/assets/studio-sfx";
fs.mkdirSync(OUT, { recursive: true });

const SR = 48000;
/** name -> [duration s, aevalsrc expression, extra audio filters] */
const SOUNDS = {
  // band-limited noise whooshes, fast attack + long tail: arm swings / throws (3 pitches)
  ...Object.fromEntries(
    [
      [0, 700, 0.38],
      [1, 1100, 0.3],
      [2, 520, 0.5],
    ].map(([i, f, d]) => [
      `whoosh_00${i}`,
      [d, `(random(0)*2-1)*if(lt(t,${(d * 0.22).toFixed(3)}),pow(t/${(d * 0.22).toFixed(3)},1.5),pow((${d}-t)/${(d * 0.78).toFixed(3)},1.8))`, `highpass=f=${f * 0.5},lowpass=f=${f * 3},bandpass=f=${f}:width_type=o:w=2.2,volume=6`],
    ]),
  ),
  // slide whistle down (falls) and up (jumps / rising anticipation), with vibrato
  slideDown_000: [0.7, "0.55*sin(2*PI*(1500*t-850*t*t)+1.2*sin(2*PI*7*t))*min(1,t*30)*min(1,(0.7-t)*8)", "lowpass=f=5000"],
  slideUp_000: [0.45, "0.5*sin(2*PI*(420*t+1100*t*t)+0.8*sin(2*PI*8*t))*min(1,t*30)*min(1,(0.45-t)*10)", "lowpass=f=5000"],
  // spring boing: pitch wobble decaying into the tone
  boing_000: [0.6, "0.6*(sin(2*PI*190*t+3.2*sin(2*PI*13*t)*exp(-3*t))+0.35*sin(2*PI*380*t+6.4*sin(2*PI*13*t)*exp(-3*t)))*exp(-4*t)*min(1,t*200)", "lowpass=f=4000"],
  // apple crunch: dense decaying noise grains (3 variants)
  ...Object.fromEntries(
    [0, 1, 2].map((i) => [
      `crunch_00${i}`,
      [0.28 + i * 0.03, `(random(0)*2-1)*exp(-${55 + i * 12}*mod(t,${(0.031 + i * 0.006).toFixed(3)}))*exp(-${7 + i}*t)*min(1,t*400)`, `highpass=f=700,lowpass=f=7500,volume=1.6`],
    ]),
  ),
  // pop: apple snapping off the twig
  pop_000: [0.12, "0.8*sin(2*PI*(520*t+5200*t*t))*exp(-34*t)*min(1,t*800)", "highpass=f=200"],
  // gulp / swallow
  gulp_000: [0.22, "0.7*sin(2*PI*(260*t-300*t*t))*exp(-12*t)*min(1,t*300)+0.25*sin(2*PI*(130*t))*exp(-18*t)", "lowpass=f=2500"],
};

for (const [name, [dur, expr, filters]] of Object.entries(SOUNDS)) {
  const file = path.join(OUT, `${name}.ogg`);
  const args = [
    "-v", "error", "-y",
    "-f", "lavfi", "-i", `aevalsrc=exprs='${expr}':s=${SR}:d=${dur}`,
    "-af", `${filters},alimiter=limit=0.89,afade=t=out:st=${(dur - 0.02).toFixed(3)}:d=0.02`,
    "-ac", "1", "-c:a", "libvorbis", "-q:a", "6",
    "-map_metadata", "-1", "-fflags", "+bitexact", "-flags:a", "+bitexact",
    file,
  ];
  const r = spawnSync("ffmpeg", args, { stdio: "inherit" });
  if (r.status !== 0) process.exit(r.status ?? 1);
  console.log(file);
}

fs.writeFileSync(
  path.join(OUT, "asset.json"),
  JSON.stringify(
    {
      id: "studio-sfx",
      alias: "studio",
      kind: "sfx",
      title: "Studio procedural cartoon SFX",
      author: "Stickman Video Factory (generated by scripts/make-sfx.mjs)",
      origin: "generated",
      generator: "scripts/make-sfx.mjs",
      source: "own work: FFmpeg aevalsrc synthesis with seeded noise (scripts/make-sfx.mjs)",
      license: "CC0-1.0",
      licenseUrl: "http://creativecommons.org/publicdomain/zero/1.0/",
      licenseFile: "LICENSE.txt",
      retrieved: "generated",
      notes: "Own work: synthesized from mathematical expressions, no samples. Regenerate with `node scripts/make-sfx.mjs`.",
    },
    null,
    2,
  ) + "\n",
);
fs.writeFileSync(
  path.join(OUT, "LICENSE.txt"),
  "Studio procedural cartoon SFX — generated by scripts/make-sfx.mjs (Stickman Video Factory).\n" +
    "Synthesized from mathematical expressions with FFmpeg; contains no third-party recordings.\n" +
    "Dedicated to the public domain: CC0 1.0 Universal — http://creativecommons.org/publicdomain/zero/1.0/\n",
);
